-- Las asignaciones actuales conservan sus IDs, nombres y notas hasta que el
-- administrador elige explícitamente continuar una de ellas.
CREATE TABLE subject_series (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id),
  shift_id INTEGER NOT NULL REFERENCES shifts(id),
  part_count INTEGER NOT NULL CHECK(part_count>=2),
  completed BOOLEAN NOT NULL DEFAULT false,
  UNIQUE(id,subject_id,shift_id)
);
ALTER TABLE offerings ADD COLUMN series_id INTEGER;
ALTER TABLE offerings ADD COLUMN part_number INTEGER;
ALTER TABLE offerings ADD COLUMN part_recovery BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE offerings ADD CONSTRAINT offerings_series_identity
  FOREIGN KEY(series_id,subject_id,shift_id) REFERENCES subject_series(id,subject_id,shift_id);
ALTER TABLE offerings ADD CONSTRAINT offerings_part_valid CHECK (
  (series_id IS NULL AND part_number IS NULL AND NOT part_recovery)
  OR (series_id IS NOT NULL AND part_number IS NOT NULL AND part_number>=1)
);
CREATE UNIQUE INDEX offerings_original_part_unique ON offerings(series_id,part_number)
  WHERE series_id IS NOT NULL AND NOT part_recovery;
CREATE INDEX offerings_series_idx ON offerings(series_id,part_number);
