CREATE TABLE academic_groups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id),
  year_id INTEGER NOT NULL REFERENCES years(id),
  admission_year_id INTEGER NOT NULL REFERENCES years(id),
  shift_id INTEGER NOT NULL REFERENCES shifts(id),
  offering_id INTEGER UNIQUE REFERENCES offerings(id),
  UNIQUE(subject_id,year_id,admission_year_id,shift_id)
);
CREATE TABLE academic_group_students (
  group_id INTEGER NOT NULL REFERENCES academic_groups(id),
  student_id INTEGER NOT NULL REFERENCES students(user_id),
  PRIMARY KEY(group_id,student_id)
);
CREATE INDEX academic_group_student_idx ON academic_group_students(student_id);
