CREATE TABLE study_plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 160),
  career_id INTEGER NOT NULL REFERENCES careers(id),
  level INTEGER NOT NULL CHECK (level BETWEEN 1 AND 3),
  original_name TEXT NOT NULL CHECK (char_length(original_name) BETWEEN 1 AND 200),
  content BYTEA NOT NULL,
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 16 AND 20971520),
  uploaded_by INTEGER NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (octet_length(content)=size_bytes)
);
CREATE INDEX study_plans_career_level_idx ON study_plans(career_id,level,created_at DESC);
